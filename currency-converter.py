#كود لتحويل مبلغ من الدينار الاردني الى اليورو
#ادخال المستخدم قيمةالمبلغ الذي يريد تحويله
currency=float(input("enter a value in JD"))
#ادخال المستخدم سعر الصرف للعملة التي يريد التحويل اليها
currency_eur=float(input("enter the rate of the eur"))
#ضرب المبلغ بسعر الصرف لاخراج المبلغ المحول
total=currency*currency_eur
#حساب العمولة بضرب المبلغ ب 3 بالمئة
commission=currency*0.03
#قمت بعمل التحسين الاول بعرض المبلغ المحول دون حساب العمولة اولاً ليعرف المستخدم المبلغ قبل وبعد اضافة العمولة
#طباعة المبلغ دون حساب العمولة
print("the cost without commission",total)
#طباعة المبلغ المحول كاملاً
print("the cost with commission",commission+total)


